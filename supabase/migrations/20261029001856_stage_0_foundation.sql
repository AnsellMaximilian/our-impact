-- Our Impact Stage 0 foundation
-- Tenant-aware campaign setup, curated mock organizations, and a safe public read path.

create schema if not exists private;

create table public.profiles (
  id uuid primary key references auth.users (id) on delete cascade,
  display_name text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint profiles_display_name_length check (
    display_name is null or char_length(display_name) between 2 and 80
  )
);

create table public.companies (
  id uuid primary key default gen_random_uuid(),
  name text not null,
  public_name text not null,
  slug text not null unique,
  created_by uuid references auth.users (id) on delete restrict,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint companies_name_length check (char_length(name) between 2 and 120),
  constraint companies_public_name_length check (char_length(public_name) between 2 and 120),
  constraint companies_slug_format check (slug ~ '^[a-z0-9]+(?:-[a-z0-9]+)*$')
);

create table public.memberships (
  company_id uuid not null references public.companies (id) on delete cascade,
  user_id uuid not null references auth.users (id) on delete cascade,
  role text not null,
  created_at timestamptz not null default now(),
  primary key (company_id, user_id),
  constraint memberships_role check (role in ('owner', 'admin', 'viewer'))
);

create index memberships_user_id_idx on public.memberships (user_id);

create table public.organizations (
  id bigint generated by default as identity primary key,
  slug text not null unique,
  name text not null,
  short_description text not null,
  category text not null,
  country_code text not null default 'ID',
  website_url text,
  verification_state text not null default 'fictional',
  brand_color text not null default '#1f6f5c',
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  constraint organizations_slug_format check (slug ~ '^[a-z0-9]+(?:-[a-z0-9]+)*$'),
  constraint organizations_name_length check (char_length(name) between 2 and 120),
  constraint organizations_description_length check (char_length(short_description) between 10 and 280),
  constraint organizations_country_code check (country_code ~ '^[A-Z]{2}$'),
  constraint organizations_verification_state check (
    verification_state in ('fictional', 'unverified', 'verified')
  ),
  constraint organizations_brand_color check (brand_color ~ '^#[0-9A-Fa-f]{6}$')
);

create table public.campaigns (
  id uuid primary key default gen_random_uuid(),
  company_id uuid not null references public.companies (id) on delete cascade,
  public_id text not null unique,
  title text not null,
  summary text not null,
  budget_minor bigint not null,
  currency text not null default 'USD',
  timezone text not null default 'Asia/Jakarta',
  period_cadence text not null default 'weekly',
  allocation_model text not null default 'proportional',
  status text not null default 'draft',
  created_by uuid references auth.users (id) on delete restrict,
  published_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint campaigns_public_id_format check (public_id ~ '^[a-z0-9]+(?:-[a-z0-9]+)*$'),
  constraint campaigns_title_length check (char_length(title) between 3 and 120),
  constraint campaigns_summary_length check (char_length(summary) between 20 and 280),
  constraint campaigns_budget_positive check (budget_minor > 0),
  constraint campaigns_currency check (currency ~ '^[A-Z]{3}$'),
  constraint campaigns_timezone_not_blank check (char_length(timezone) between 3 and 80),
  constraint campaigns_period_cadence check (period_cadence in ('daily', 'weekly')),
  constraint campaigns_allocation_model check (
    allocation_model in ('winner_takes_all', 'proportional', 'hybrid')
  ),
  constraint campaigns_status check (status in ('draft', 'published', 'paused', 'archived')),
  constraint campaigns_published_at check (
    (status = 'published' and published_at is not null)
    or (status <> 'published')
  )
);

create index campaigns_company_id_idx on public.campaigns (company_id);
create index campaigns_created_by_idx on public.campaigns (created_by);
create index campaigns_public_status_idx on public.campaigns (public_id, status);

create table public.campaign_organizations (
  id bigint generated always as identity primary key,
  campaign_id uuid not null references public.campaigns (id) on delete cascade,
  organization_id bigint not null references public.organizations (id) on delete restrict,
  display_order smallint not null,
  created_at timestamptz not null default now(),
  unique (campaign_id, organization_id),
  unique (campaign_id, display_order),
  constraint campaign_organizations_display_order check (display_order between 1 and 5)
);

create index campaign_organizations_organization_id_idx
  on public.campaign_organizations (organization_id);

create or replace function private.set_updated_at()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

create trigger profiles_set_updated_at
before update on public.profiles
for each row execute function private.set_updated_at();

create trigger companies_set_updated_at
before update on public.companies
for each row execute function private.set_updated_at();

create trigger campaigns_set_updated_at
before update on public.campaigns
for each row execute function private.set_updated_at();

create or replace function private.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  insert into public.profiles (id, display_name)
  values (new.id, nullif(trim(new.raw_user_meta_data ->> 'display_name'), ''));
  return new;
end;
$$;

create trigger on_auth_user_created
after insert on auth.users
for each row execute function private.handle_new_user();

create or replace function private.handle_new_company()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  if new.created_by is not null then
    insert into public.memberships (company_id, user_id, role)
    values (new.id, new.created_by, 'owner');
  end if;
  return new;
end;
$$;

create trigger on_company_created
after insert on public.companies
for each row execute function private.handle_new_company();

